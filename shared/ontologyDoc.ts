/**
 * The ontology reference (docs/ontology.md) as text, derived from the schema and the action
 * registry. Pure: no filesystem, no database. `scripts/ontology-doc.ts` writes the result and
 * `--check` fails when the committed file differs from it.
 */
import {
  ACTION_NAMES,
  type ActionName,
  LINKS,
  OBJECT_TYPES,
  OPERATIONS_TYPES,
  type ObjectTypeName,
} from "./schema.js";

/** What the reference needs to know about one action parameter (server/actions/types.ts ParamDef). */
export interface ParamDoc {
  readonly type: string | { readonly object: string };
  readonly nullable?: boolean;
}

export interface ActionDoc {
  readonly params: Readonly<Record<string, ParamDoc>>;
}

/** The input bounds applied to every action parameter (server/actions/params.ts). */
export interface ParamLimits {
  readonly maxString: number;
  readonly maxList: number;
  readonly maxListItem: number;
}

const n = (value: number): string => value.toLocaleString("en-US");

function typeText(type: ParamDoc["type"]): string {
  return typeof type === "object" ? `${type.object} (primary key)` : type;
}

function objectSection(name: ObjectTypeName): string {
  const def = OBJECT_TYPES[name];
  const rows = Object.entries<string>(def.properties).map(
    ([prop, type]) => `| \`${prop}\` | ${type} | ${prop === def.primaryKey ? "primary key" : ""} |`,
  );
  const measured = (OPERATIONS_TYPES as readonly string[]).includes(name);
  return [
    `### ${name}`,
    "",
    `Table \`${def.table}\`, primary key \`${def.primaryKey}\`, ${Object.keys(def.properties).length} properties.${measured ? " An operations record: written outside any action's transaction, left out of the reset snapshot." : ""}`,
    "",
    "| Property | Type | Note |",
    "| --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function actionSection(name: ActionName, def: ActionDoc | undefined): string {
  if (def === undefined) {
    throw new Error(`Action ${name} is in ACTION_NAMES but has no definition in the registry.`);
  }
  const params = Object.entries(def.params);
  return [
    `### ${name}`,
    "",
    params.length === 0
      ? "No parameters."
      : [
          "| Parameter | Type | Required |",
          "| --- | --- | --- |",
          ...params.map(
            ([p, d]) =>
              `| \`${p}\` | ${typeText(d.type)} | ${d.nullable === true ? "no" : "yes"} |`,
          ),
        ].join("\n"),
  ].join("\n");
}

export function renderOntology(
  actions: Readonly<Partial<Record<ActionName, ActionDoc>>>,
  limits: ParamLimits,
): string {
  const types = Object.keys(OBJECT_TYPES) as ObjectTypeName[];
  return [
    "# Ontology reference",
    "",
    "Generated by `npm run ontology:doc` from [`shared/schema.ts`](../shared/schema.ts) and the action registry in [`server/actions/`](../server/actions/). Never edited by hand; CI runs `npm run ontology:doc -- --check` and fails when this file is out of date.",
    "",
    `The ontology has ${types.length} object types, ${LINKS.length} traversed links and ${ACTION_NAMES.length} actions. Each object type is one Postgres table with one quoted camelCase column per property. Every object has a string primary key.`,
    "",
    "## Object types",
    "",
    types.map(objectSection).join("\n\n"),
    "",
    "## Links",
    "",
    "Only the links the screens traverse are declared. Each is a join table between two object types.",
    "",
    "| Source | Link | Target | Join table | Source column | Target column |",
    "| --- | --- | --- | --- | --- | --- |",
    ...LINKS.map(
      (l) =>
        `| ${l.source} | \`${l.name}\` | ${l.target} | \`${l.joinTable}\` | \`${l.sourceColumn}\` | \`${l.targetColumn}\` |`,
    ),
    "",
    "## Actions",
    "",
    `Every write is one of these named actions, run in one transaction. Parameters are checked against the declarations below before the handler runs: a missing required parameter, an unknown parameter or a wrong type is refused, an object parameter must name an existing object of that type, a string is at most ${n(limits.maxString)} characters, and a list holds at most ${n(limits.maxList)} strings of at most ${n(limits.maxListItem)} characters. Rules that depend on an object's state (for example that a rule is pending before it can be approved) are enforced inside each handler and are not declared here.`,
    "",
    ACTION_NAMES.map((a) => actionSection(a, actions[a])).join("\n\n"),
    "",
  ].join("\n");
}
