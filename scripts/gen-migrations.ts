import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Bundles server/db/migrations/*.sql into server/db/migrations.generated.ts. The Worker cannot read
// the directory at runtime, and tsx and Vite would each need their own way to import .sql text, so
// the SQL is embedded as strings instead. A test fails when the two drift apart; rerun
// `npm run migrations:gen` after adding or editing a migration.
const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../server/db");
const files = readdirSync(path.join(dir, "migrations"))
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((file) => {
  const m = /^(\d{4})_([a-z0-9_]+)\.sql$/.exec(file);
  if (!m) {
    throw new Error(`Migration file "${file}" must be named NNNN_name.sql`);
  }
  const sql = readFileSync(path.join(dir, "migrations", file), "utf8");
  return `  { version: ${Number(m[1])}, name: ${JSON.stringify(m[2])}, sql: ${JSON.stringify(sql)} },`;
});

writeFileSync(
  path.join(dir, "migrations.generated.ts"),
  `// Generated by scripts/gen-migrations.ts from server/db/migrations/*.sql. Do not edit by hand.
import type { Migration } from "./migrate.js";

export const MIGRATIONS: readonly Migration[] = [
${entries.join("\n")}
];
`,
);
console.log(`Bundled ${files.length} migrations into server/db/migrations.generated.ts`);
