/**
 * The evaluation report: build it from the pipeline and the rule-recovery run, test it against
 * its floors, render it as JSON and Markdown, and say whether committed copies are stale. Pure.
 */
import type { EvalReport } from "../../shared/evalReport.js";
import type { ObjectOf } from "../../shared/schema.js";
import { PROVIDERS } from "../enrichment/providers.js";
import { EXTRACTION_PROMPT_VERSION } from "../extraction/contract.js";
import { DOCUMENT_VERSION } from "../extraction/documents.js";
import { computeMetrics, rate } from "./metrics.js";
import { evaluateFirms } from "./pipeline.js";
import { evaluateRuleRecovery } from "./rules.js";

/**
 * The least each figure may measure before the report fails, a little under what the committed
 * recordings measure, so a regression fails CI. Keyed by path into the report; the two extra
 * paths below are derived: `ruleRecovery.recoveryRate` is recovered over planted.
 */
export const THRESHOLDS: Readonly<Record<string, number>> = {
  "providers.beacondb.precision": 0.95,
  "providers.dealdb.precision": 0.95,
  "providers.filings.precision": 0.92,
  "providers.websearch.precision": 0.8,
  "reconciled.coverage": 0.65,
  "reconciled.precision": 0.9,
  "reconciled.higherTrustRight": 0.85,
  "abstention.calibration": 0.95,
  tierAgreement: 0.5,
  "ruleRecovery.recoveryRate": 1,
};

export async function buildReport(
  firms: readonly ObjectOf<"Firm">[],
  rows: readonly ObjectOf<"Extraction">[],
): Promise<EvalReport> {
  const evals = evaluateFirms(firms, rows);
  const models = [...new Set(evals.map((e) => e.extractionModel))].sort();
  const report: EvalReport = {
    version: 1,
    generatedFrom: {
      documents: DOCUMENT_VERSION,
      prompt: EXTRACTION_PROMPT_VERSION,
      fixtures: models.length === 0 ? "rule-based" : models.join(" + "),
    },
    ...computeMetrics(evals),
    recordedRun: { values: rows.length, grounded: rows.filter((r) => r.grounded).length },
    ruleRecovery: await evaluateRuleRecovery(firms),
    thresholds: { ...THRESHOLDS },
    passed: true,
  };
  return { ...report, passed: failedThresholds(report).length === 0 };
}

/** The measured figure at a threshold's path, or null when it could not be measured. */
function measured(report: EvalReport, path: string): number | null {
  const [head, name, field] = path.split(".");
  if (head === "providers") {
    const p = report.providers.find((x) => x.provider === name);
    return p === undefined ? null : (p[field as "coverage" | "precision"] ?? null);
  }
  if (path === "ruleRecovery.recoveryRate") {
    return rate(report.ruleRecovery.recovered, report.ruleRecovery.planted);
  }
  if (path === "tierAgreement") {
    return report.tierAgreement;
  }
  const group = report[head as "reconciled" | "abstention"] as Record<string, number | null>;
  return group[name] ?? null;
}

/** The thresholds the report does not reach. A figure that could not be measured fails. */
export function failedThresholds(report: EvalReport): string[] {
  return Object.entries(report.thresholds)
    .filter(([path, floor]) => {
      const value = measured(report, path);
      return value === null || value < floor;
    })
    .map(([path]) => path);
}

export const renderJson = (report: EvalReport): string => `${JSON.stringify(report, null, 2)}\n`;

const pct = (v: number | null): string => (v === null ? "n/a" : `${(v * 100).toFixed(1)}%`);

const groundedText = ({ recordedRun: run }: EvalReport): string =>
  run.values === 0
    ? "n/a"
    : `${run.grounded.toLocaleString("en-US")} of ${run.values.toLocaleString("en-US")} (${pct(run.grounded / run.values)})`;

const table = (head: readonly string[], rows: readonly (readonly string[])[]): string =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");

export function renderMarkdown(report: EvalReport): string {
  const { reconciled: rec, abstention: abs, ruleRecovery: rules } = report;
  const label = (id: string): string => PROVIDERS[id as keyof typeof PROVIDERS]?.label ?? id;
  const thresholdRows = Object.entries(report.thresholds).map(([path, floor]) => {
    const value = measured(report, path);
    return [
      `\`${path}\``,
      pct(floor),
      pct(value),
      value !== null && value >= floor ? "pass" : "fail",
    ];
  });
  return `# Evaluation against synthetic ground truth

Beacon's agent reads each firm's source records, keeps only values it can quote, reconciles what the sources say, and scores the firm with the rubric. This page measures that work. The universe is generated, so every firm has a hidden true value for every axis and the agent's output can be checked exactly. Every figure below is measured against synthetic ground truth. None of them says how the agent would do on real firms.

Generated by \`npm run eval\` (never edited by hand). The same figures are in [evals.json](evals.json).

## What was run

${table(
  ["Item", "Value"],
  [
    ["Firms", String(report.firms)],
    ["Source records", report.generatedFrom.documents],
    ["Extraction prompt", report.generatedFrom.prompt],
    ["Extraction read", report.generatedFrom.fixtures],
    ["Recorded values that passed grounding", groundedText(report)],
    ["Result", report.passed ? "all thresholds met" : "a threshold failed"],
  ],
)}

The extraction is read from the committed recordings, so the run needs no network and gives the same figures every time. The grounding row counts recorded answers whose quote is in the source record and states the value. It says whether an answer quotes its record faithfully, not whether the value is right: the records include each provider's deliberate errors, which the sections below score against the truth.

## Providers

Against synthetic ground truth. Per provider, over the firm axes it covers. Coverage is the share with a reading that survived grounding. Precision is the share of those readings that match the truth.

${table(
  ["Provider", "Coverage", "Precision"],
  report.providers.map((p) => [label(p.provider), pct(p.coverage), pct(p.precision)]),
)}

A value matches the truth when it is the same label or true/false answer. A number matches when it falls in the same rubric band as the truth, because it then earns the same score.

## Reconciliation

Against synthetic ground truth. Over every firm axis the agent enriches.

${table(
  ["Measure", "Value", "Meaning"],
  [
    ["Coverage", pct(rec.coverage), "Axes where the agent settled on one value"],
    ["Precision", pct(rec.precision), "Settled values that match the truth"],
    [
      "Conflict rate",
      pct(rec.conflictRate),
      "Axes with a reading where sources disagree and the agent leaves the choice to the analyst",
    ],
    [
      "Higher-trust right",
      pct(rec.higherTrustRight),
      "Conflicts where the more trusted source is the one that matches the truth",
    ],
  ],
)}

## Abstention

Against synthetic ground truth. The agent records no value when no source supplies one.

${table(
  ["Measure", "Value", "Meaning"],
  [
    ["Abstention rate", pct(abs.rate), "Axes where the agent recorded no value"],
    ["Calibration", pct(abs.calibration), "Abstentions where no provider's record stated the axis"],
  ],
)}

## Tier agreement

Against synthetic ground truth: ${pct(report.tierAgreement)} of firms get the same tier from the agent's settled values as from the true values. Axes the agent abstained on or left in conflict count as unknown, so this is the tier before an analyst finishes the enrichment.

## Rule recovery

Against synthetic ground truth. The seed's rejection patterns are planted in memory (small firms, generalists, small deals, low deal volume, plus rejections that no screening rule can express) and the ${rules.method} clusterer proposes screening rules from them. It recovered ${rules.recovered} of ${rules.planted} planted patterns. This clusterer matches rationale wording and firm facts against a fixed list of candidate rules, so the figure checks the learning loop end to end; it does not measure open-ended discovery.

## Thresholds

Each figure has a floor, a little under the committed measurement. \`npm run eval -- --check\` fails when a figure falls below its floor.

${table(["Measure", "Floor", "Measured", "Result"], thresholdRows)}

## Limits

- The universe, the sources and their errors are generated. The figures say the pipeline does what it should on this data, not how it would do on real firms.
- Precision counts a numeric reading in the right rubric band as correct, even when the figure itself differs.

## Reproduce

\`\`\`
npm run eval            # regenerate docs/evals.md and docs/evals.json
npm run eval -- --check # exit non-zero if a threshold fails or the committed files are stale
\`\`\`
`;
}

/**
 * The committed files that differ from what was just generated; a missing file is stale.
 * Keys are repository paths.
 */
export function staleFiles(
  committed: Readonly<Record<"docs/evals.json" | "docs/evals.md", string | null>>,
  fresh: { json: string; md: string },
): string[] {
  const expected = { "docs/evals.json": fresh.json, "docs/evals.md": fresh.md } as const;
  return (Object.keys(expected) as (keyof typeof expected)[]).filter(
    (path) => committed[path] !== expected[path],
  );
}
